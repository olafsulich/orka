// Autonomy level per target repo, kept on orka's side (never in the target repo):
// <config dir>/orka/config.json {"repos": {"<repo path>": {"autonomy": "L1"}}}.
// The CLI enforces it: orka push / land refuse above the level, and the git hooks orka
// installs for job panes refuse commits, merges and pushes above it.
import { existsSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

export const LEVELS = ["L0", "L1", "L2", "L3"];
export const DEFAULT_LEVEL = "L1";
export const LEVEL_TEXT = {
  L0: "read-only: no commits",
  L1: "branch and commit (default)",
  L2: "L1 plus push of job branches and PRs",
  L3: "L2 plus merge into main and push of main",
};
// The lowest level each action needs.
export const ACTIONS = {
  commit: "L1",
  push: "L2",
  pr: "L2",
  "commit-main": "L3",
  merge: "L3",
  "push-main": "L3",
};
export const MAIN_BRANCHES = ["main", "master"];

export function configFile(env = process.env) {
  const dir = env.ORKA_CONFIG_DIR || env.ORCA_CONFIG_DIR || join(env.XDG_CONFIG_HOME || join(homedir(), ".config"), "orka");
  return join(dir, "config.json");
}

function repoKey(repo) {
  try {
    return realpathSync(repo);
  } catch {
    return resolve(repo);
  }
}

function readConfig(path) {
  if (!existsSync(path)) return {};
  try {
    return JSON.parse(readFileSync(path, "utf8")) || {};
  } catch {
    const err = new Error(`corrupt orka config ${path}`);
    err.orka = true;
    throw err;
  }
}

// { level, source }: source is "default" or the config file.
export function readLevel(repo, env = process.env) {
  const path = configFile(env);
  const level = readConfig(path).repos?.[repoKey(repo)]?.autonomy;
  if (LEVELS.includes(level)) return { level, source: path };
  return { level: DEFAULT_LEVEL, source: "default" };
}

export function writeLevel(repo, level, env = process.env) {
  const path = configFile(env);
  const cfg = readConfig(path);
  cfg.repos = cfg.repos || {};
  cfg.repos[repoKey(repo)] = { ...(cfg.repos[repoKey(repo)] || {}), autonomy: level };
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(`${path}.tmp`, JSON.stringify(cfg, null, 2) + "\n");
  renameSync(`${path}.tmp`, path);
  return path;
}

export const rank = (level) => LEVELS.indexOf(level);

// { ok, need } for one action at one level.
export function allows(level, action) {
  const need = ACTIONS[action];
  if (!need) {
    const err = new Error(`unknown action ${action}; one of: ${Object.keys(ACTIONS).join(", ")}`);
    err.orka = true;
    throw err;
  }
  // L0 is read-only, so even a commit on a branch is refused.
  return { ok: rank(level) >= rank(need), need };
}

export function refusal(repo, level, source, action, need) {
  return `orka: refused ${action}: ${repo} is at autonomy ${level}${source === "default" ? " (default)" : ""}; ${action} needs ${need}. Levels are set by Olaf with orka autonomy set, never from a job.`;
}

// pre-push stdin: "<local ref> <local oid> <remote ref> <remote oid>" per line.
export function pushActions(stdin, mains = MAIN_BRANCHES) {
  const out = new Set();
  for (const line of String(stdin || "").split("\n")) {
    const remoteRef = line.trim().split(/\s+/)[2];
    if (!remoteRef) continue;
    out.add(mains.some((b) => remoteRef === `refs/heads/${b}`) ? "push-main" : "push");
  }
  return [...out];
}

// The guard hooks job panes use (core.hooksPath via GIT_CONFIG_* env). Each one asks orka, then
// runs the repo's own hook of the same name, so husky and friends keep working.
export function hookScripts(node, orka) {
  const chain = `orig=$(env -u GIT_CONFIG_COUNT -u GIT_CONFIG_KEY_0 -u GIT_CONFIG_VALUE_0 git config --get core.hooksPath)
if [ -z "$orig" ]; then orig="$(git rev-parse --git-common-dir)/hooks"; fi
case "$orig" in /*) ;; *) orig="$(git rev-parse --show-toplevel)/$orig";; esac
here=$(cd "$(dirname "$0")" && pwd)
run_orig() { [ "$(cd "$orig" 2>/dev/null && pwd)" != "$here" ] && [ -x "$orig/$1" ]; }`;
  const head = `#!/bin/sh
# Generated by orka: autonomy guard for job panes. Do not edit; orka run rewrites it.
${chain}`;
  const q = (s) => `'${String(s).replaceAll("'", `'\\''`)}'`;
  const check = (action, hook) => `${q(node)} ${q(orka)} autonomy check ${action} --hook ${hook} --cwd "$PWD"`;
  return {
    "pre-commit": `${head}
${check("commit", "pre-commit")} || exit 1
if run_orig pre-commit; then exec "$orig/pre-commit" "$@"; fi
exit 0
`,
    "pre-merge-commit": `${head}
${check("merge", "pre-merge-commit")} || exit 1
if run_orig pre-merge-commit; then exec "$orig/pre-merge-commit" "$@"; fi
exit 0
`,
    "pre-push": `${head}
input=$(cat)
printf '%s\\n' "$input" | ${check("push", "pre-push")} --stdin || exit 1
if run_orig pre-push; then printf '%s\\n' "$input" | "$orig/pre-push" "$@"; exit $?; fi
exit 0
`,
  };
}
